const mongoose = require('mongoose');

const AgentMatchSchema = new mongoose.Schema(
  {
    user_id: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true
    },
    conference_id: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Conference',
      required: true,
      index: true
    },
    match_score: {
      type: Number,
      min: 0,
      max: 100,
      default: 85
    },
    match_reasoning: {
      type: String,
      required: [true, 'Match reasoning generated by Agent is required']
    },
    status: {
      type: String,
      enum: ['unread', 'saved', 'dismissed'],
      default: 'unread',
      index: true
    },
    criteria_alignment: {
      topic_relevance: { type: String, default: 'High' },
      reputation_rating: { type: String, default: 'Verified' },
      location_fit: { type: String, default: 'Matches Criteria' },
      deadline_urgency: { type: String, default: 'Upcoming' }
    }
  },
  {
    timestamps: { createdAt: 'created_at', updatedAt: 'updated_at' }
  }
);

AgentMatchSchema.index({ user_id: 1, conference_id: 1 }, { unique: true });

module.exports = mongoose.model('AgentMatch', AgentMatchSchema);
